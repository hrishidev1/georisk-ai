from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from app.models import RasterType
from app.processing.enums import ProcessingStatus
from app.raster.models import RasterMetadata
from app.processing.enums import ProcessorType

@dataclass(slots=True, frozen=True)
class GeneratedRaster:
    """
    A raster generated by a processor.

    The ProcessingManager will persist this as a Raster
    record after successful execution.
    """

    name: str

    raster_type: RasterType

    file_path: Path

    processor: ProcessorType

    processor_version: str

    parameters: dict[str, Any]

    extension: str = ".tif"

    description: str | None = None

    metadata: RasterMetadata | None = None


@dataclass(slots=True, frozen=True)
class GeneratedVector:
    """
    A vector artifact generated by a processor.
    
    The ProcessingManager will persist this as a VectorLayer
    record after successful execution in the future.
    """

    name: str

    artifact_type: str

    file_path: Path

    processor: ProcessorType

    processor_version: str

    parameters: dict[str, Any]

    extension: str = ".gpkg"

    description: str | None = None

    geometry_type: str | None = None

    crs: str | None = None

    feature_count: int | None = None



@dataclass(slots=True, frozen=True)
class ProcessingResult:
    """
    Standard result returned by every processor.
    """

    status: ProcessingStatus

    outputs: list[GeneratedRaster] = field(
        default_factory=list,
    )

    vector_outputs: list[GeneratedVector] = field(
        default_factory=list,
    )

    metadata: dict[str, Any] = field(
        default_factory=dict,
    )

    warnings: list[str] = field(
        default_factory=list,
    )

    logs: list[str] = field(
        default_factory=list,
    )

    execution_time: float | None = None

    processor: ProcessorType | None = None

    processor_version: str | None = None

    parameters: dict[str, Any] = field(
        default_factory=dict,
    )